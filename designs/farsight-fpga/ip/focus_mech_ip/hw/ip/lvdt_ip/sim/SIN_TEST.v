`timescale 1ns/100ps

module SIN_TEST;

parameter SYSCLK_PERIOD = 10;// 50MHZ

reg SYSCLK;
reg NSYSRESET;

wire [7:0] o_data;

initial
begin
    SYSCLK = 1'b0;
    NSYSRESET = 1'b0;
end

//////////////////////////////////////////////////////////////////////
// Reset Pulse
//////////////////////////////////////////////////////////////////////
initial
begin
    #(SYSCLK_PERIOD * 10 )
        NSYSRESET = 1'b1;
end


//////////////////////////////////////////////////////////////////////
// Clock Driver
//////////////////////////////////////////////////////////////////////
always @(SYSCLK)
    #(SYSCLK_PERIOD / 2.0) SYSCLK <= !SYSCLK;


//////////////////////////////////////////////////////////////////////
// Instantiate Unit Under Test:  top
//////////////////////////////////////////////////////////////////////
top top_0 (
    // Inputs
    .REF_CLK_0(SYSCLK),
    .i_RESETn(NSYSRESET),

    // Outputs
    .DATA_OUT(o_data)

    // Inouts

);

endmodule

